import assert from "node:assert/strict";
import { bubbleHold, chatPayload, noKeyLine, onlyBearEmoji, speakable, splitWords, scrollProgress, slotAt, stampFor, stripTrick } from "./lib.ts";

const vh = 800;
assert.equal(scrollProgress(1000, 600, vh), 0, "below the fold: not started");
assert.equal(scrollProgress(600, 600, vh), 0, "top at 75%: just starting");
assert.equal(scrollProgress(400 - 600, 600, vh), 1, "bottom at 50%: done");
assert.equal(scrollProgress(-5000, 600, vh), 1, "scrolled past: clamped");
const mid = scrollProgress(200, 600, vh);
assert.ok(mid > 0 && mid < 1);
assert.ok(scrollProgress(100, 600, vh) > mid, "monotonic as you scroll down");
assert.equal(scrollProgress(0, 0, 0), 0, "zero-size guard");

assert.equal(stampFor(10), "×10");
assert.equal(stampFor(100), "×100");
assert.equal(stampFor(11), null);
assert.equal(stampFor(0), null);

assert.deepEqual(stripTrick("Hi! [trick:wave]"), { text: "Hi!", trick: "wave" });
assert.deepEqual(stripTrick("Sure, a wave! 🌤️ [trick:wave]"), { text: "Sure, a wave!", trick: "wave" });
assert.equal(onlyBearEmoji("biscuits 🌟 and hugs 🧸 👋🏽 🇩🇰!"), "biscuits and hugs 🧸!");
assert.equal(speakable("Hi there 🧸 friend 👨‍👩‍👧!"), "Hi there friend!");
assert.deepEqual(stripTrick("Hi [tri"), { text: "Hi", trick: null });
assert.deepEqual(stripTrick("Hi [trick:sp"), { text: "Hi", trick: null });
assert.equal(stripTrick("a [b] c").text, "a [b] c");
assert.equal(stripTrick("x [trick:nope]").trick, "nope");
const m = (role: "user" | "assistant", content: string, error?: boolean) => ({ role, content, error });
assert.deepEqual(chatPayload([m("assistant", "hey"), m("user", " q "), m("assistant", "oops", true), m("user", "again")]), [{ role: "user", content: "q" }, { role: "user", content: "again" }]);
const long = Array.from({ length: 30 }, (_, i) => m(i % 2 ? "assistant" : "user", "x"));
const p = chatPayload(long);
assert.ok(p.length <= 20 && p[0].role === "user");
assert.equal(slotAt([6, 8, 21, 0, 3], 22), 2);
assert.equal(slotAt([6, 8, 21, 0, 3], 1), 3);
assert.equal(slotAt([0, 6, 12], 7), 1);
assert.equal(slotAt([6, 12, 21], 3), 2, "before first start wraps to the last slot");
const big = Array.from({ length: 20 }, (_, i) => m(i % 2 ? "assistant" : "user", "x".repeat(800)));
const capped = chatPayload(big);
assert.ok(capped.reduce((n, x) => n + x.content.length, 0) <= 8000 && capped[0].role === "user" && capped.at(-1)!.role === "assistant", "fits the server's 8000-char cap");
assert.deepEqual(splitWords("Hi *big yawn* there"), [{ w: "Hi", em: false }, { w: "big", em: true }, { w: "yawn", em: true }, { w: "there", em: false }]);
assert.deepEqual(splitWords("*yawn* ok"), [{ w: "yawn", em: true }, { w: "ok", em: false }]);
assert.deepEqual(splitWords("a *ya"), [{ w: "a", em: false }, { w: "ya", em: true }], "open stage direction while streaming");
assert.deepEqual(splitWords("  "), []);
assert.notEqual(noKeyLine(0), noKeyLine(1));
assert.equal(noKeyLine(3), noKeyLine(0), "rotates");
assert.equal(noKeyLine(-1), noKeyLine(2));
assert.equal(bubbleHold(0), 4000);
assert.equal(bubbleHold(50), 7000);
assert.equal(bubbleHold(9999), 14000);
console.log("scroll + milestones + chat helpers ok");
